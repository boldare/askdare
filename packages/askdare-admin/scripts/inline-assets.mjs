// Turns the built dashboard into a TypeScript module, so the package hands its script and
// stylesheet to the console from memory and never reads files at runtime (ADR-0005, ADR-0032).
// Output: src/generated/assets.ts
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';

/** The dashboard's script, gzipped: Preact and our views (ADR-0032, decision 9). */
const SCRIPT_BUDGET_BYTES = 12 * 1024;
const STYLE_BUDGET_BYTES = 4 * 1024;

const read = (path) => readFile(new URL(`../${path}`, import.meta.url), 'utf8');
const [script, style] = await Promise.all([
  read('.assets/dashboard.js'),
  read('.assets/dashboard.css'),
]);

const scriptGzip = gzipSync(script).length;
const styleGzip = gzipSync(style).length;
for (const [what, size, budget] of [
  ['Dashboard script', scriptGzip, SCRIPT_BUDGET_BYTES],
  ['Dashboard styles', styleGzip, STYLE_BUDGET_BYTES],
]) {
  if (size > budget) {
    console.error(`${what} is ${size} B gzipped; the budget is ${budget} B.`);
    process.exit(1);
  }
}

const source = `// Generated by scripts/inline-assets.mjs. Do not edit.
export const DASHBOARD_JS: string = ${JSON.stringify(script)};
export const DASHBOARD_CSS: string = ${JSON.stringify(style)};
`;
await mkdir(new URL('../src/generated/', import.meta.url), { recursive: true });
await writeFile(new URL('../src/generated/assets.ts', import.meta.url), source);
console.log(`inline-assets: dashboard ${scriptGzip} B gz, styles ${styleGzip} B gz`);
