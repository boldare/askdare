// The text reference in docs/texts.md: every key of src/i18n/texts.ts with its default in each
// built-in language, written between the generated-texts markers. src/i18n/texts-doc.test.ts renders
// it with the same functions and fails when the page is out of date.
// Run: pnpm --filter @boldare/askdare docs:texts (Node strips the types itself.)
import { readFile, writeFile } from 'node:fs/promises';
import { registerHooks } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/** The command that rewrites the generated part of docs/texts.md. */
export const UPDATE_COMMAND = 'pnpm --filter @boldare/askdare docs:texts';

const pkg = join(dirname(fileURLToPath(import.meta.url)), '..');
/** The page in the repository; packages/askdare/docs/ is only the copy made by the build. */
export const TEXTS_DOC: string = join(pkg, '..', '..', 'docs', 'texts.md');

const BEGIN = '<!-- BEGIN:generated-texts -->';
const END = '<!-- END:generated-texts -->';
/** Shown for a plural category a language has no text for. */
const MISSING = '—';
/** The categories of `Intl.PluralRules` (CLDR), in their usual order. */
const PLURAL_CATEGORIES: readonly Intl.LDMLPluralRule[] = [
  'zero',
  'one',
  'two',
  'few',
  'many',
  'other',
];

/** What the reference needs from src/i18n/texts.ts. */
export interface TextsSource {
  readonly TEXT_LOCALES: readonly string[];
  readonly TEXT_KEYS: readonly string[];
  readonly textsFor: (locale: string) => Readonly<Record<string, string>>;
}

/** Keys in dictionary order, with the categories of each plural text together, in CLDR order. */
function orderedKeys(keys: readonly string[]): string[] {
  const known = new Set(keys);
  const ordered = new Set<string>();
  for (const key of keys) {
    const base = key.slice(0, key.lastIndexOf('.'));
    const forms = PLURAL_CATEGORIES.map((category) => `${base}.${category}`);
    for (const each of forms.every((form) => known.has(form)) ? forms : [key]) ordered.add(each);
  }
  return [...ordered];
}

/** A text as a table cell: pipes and backslashes escaped, line breaks as `<br>`, no raw HTML. */
function cell(text: string): string {
  return text
    .replaceAll('\\', '\\\\')
    .replaceAll('|', '\\|')
    .replaceAll('<', '&lt;')
    .replaceAll(/\r\n?|\n/g, '<br>');
}

/** The Markdown that goes between the markers: one row per key, one column per language. */
export function renderTexts(source: TextsSource): string {
  const names = new Intl.DisplayNames(['en'], { type: 'language' });
  const languages = source.TEXT_LOCALES.map((locale) => ({
    name: names.of(locale) ?? locale,
    texts: source.textsFor(locale),
  }));
  let missing = false;
  const rows = orderedKeys(source.TEXT_KEYS).map((key) => {
    const cells = languages.map(({ texts }) => {
      const text = texts[key];
      if (text === undefined) missing = true;
      return text === undefined ? MISSING : cell(text);
    });
    return `| \`${key}\` | ${cells.join(' | ')} |`;
  });
  return [
    `<!-- Generated by \`${UPDATE_COMMAND}\` from the dictionaries. Do not edit by hand. -->`,
    '',
    `| Key | ${languages.map(({ name }) => name).join(' | ')} |`,
    `| --- |${' --- |'.repeat(languages.length)}`,
    ...rows,
    ...(missing
      ? [
          '',
          `A dash (${MISSING}) means the language has no text of its own for that plural category, so the widget shows the \`other\` text.`,
        ]
      : []),
  ].join('\n');
}

/** The page with `generated` between its markers; everything around them is kept. */
export function replaceGenerated(page: string, generated: string): string {
  const start = page.indexOf(BEGIN);
  const end = page.indexOf(END);
  if (start === -1 || end < start) {
    throw new Error(`docs/texts.md must contain ${BEGIN} and then ${END}.`);
  }
  return `${page.slice(0, start + BEGIN.length)}\n${generated}\n${page.slice(end)}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  // Imports in src/ leave out the `.ts` extension (bundler resolution); Node needs it.
  registerHooks({
    resolve: (specifier, context, nextResolve) =>
      /^\.\.?\//.test(specifier) && !/\.\w+$/.test(specifier)
        ? nextResolve(`${specifier}.ts`, context)
        : nextResolve(specifier, context),
  });
  const texts = (await import(
    pathToFileURL(join(pkg, 'src', 'i18n', 'texts.ts')).href
  )) as TextsSource;
  const before = await readFile(TEXTS_DOC, 'utf8');
  const after = replaceGenerated(before, renderTexts(texts));
  if (after === before) {
    console.log('docs-texts: docs/texts.md is up to date');
  } else {
    await writeFile(TEXTS_DOC, after);
    console.log(`docs-texts: wrote ${texts.TEXT_KEYS.length} keys to docs/texts.md`);
  }
}
