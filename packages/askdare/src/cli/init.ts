import { randomBytes } from 'node:crypto';
import { appendFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative, sep } from 'node:path';
import { parseEnv } from 'node:util';
import {
  addCommand,
  findFile,
  gitIgnores,
  majorOf,
  type Project,
  readProject,
  routeDir,
  runScript,
  shown,
} from './project';

export interface InitOptions {
  readonly root: string;
  readonly botId: string;
  /** Written to `.env.local` as ASKDARE_MODEL; the library never assumes a model. */
  readonly model?: string | undefined;
  readonly print: (line: string) => void;
}

export class InitError extends Error {}

const BOT_ID = /^[a-z0-9-]{1,48}$/;

function configTemplate(botId: string): string {
  return `import { defineBot } from '@boldare/askdare';

export const bots = [
  defineBot({
    id: '${botId}',
    // Required: a current OpenAI model your project may use. Set ASKDARE_MODEL in .env.local.
    model: process.env.ASKDARE_MODEL ?? '',
    instructions: ({ locale }) =>
      [
        'You are the assistant on our website. Answer briefly and politely.',
        'If you do not know something, say so.',
        \`Reply in the language of the visitor's message; default to \${locale}.\`,
      ].join(' '),
    security: {
      // Other sites that may embed the chat, e.g. ['https://www.example.com'].
      allowedOrigins: [],
    },
    widget: {
      locale: 'auto',
      greeting: 'Hi! How can I help?',
      theme: 'aura', // aura, halo, sage or care
    },
    // Knowledge base, tools, attachments, voice and limits: see node_modules/@boldare/askdare/docs.
  }),
];
`;
}

function routeTemplate(configImport: string): string {
  return `import { createChatHandler } from '@boldare/askdare/next';
import { bots } from '${configImport}';

// Must be a literal in this file; keep it above the bots' turn timeout (120 s by default).
export const maxDuration = 300;

export const { GET, POST, DELETE } = createChatHandler({ bots });
`;
}

async function readText(file: string): Promise<string> {
  try {
    return await readFile(file, 'utf8');
  } catch {
    return '';
  }
}

/**
 * Adds the variables `.env.local` and `.env` don't mention yet; never changes existing lines.
 * Returns what it added and the variables that are still empty.
 */
async function addEnv(
  project: Project,
  model: string | undefined,
): Promise<{ added: string[]; empty: string[] }> {
  const file = join(project.root, '.env.local');
  const current = await readText(file);
  const known = { ...parseEnv(await readText(join(project.root, '.env'))), ...parseEnv(current) };
  const variables: readonly (readonly [name: string, comment: string, value: string])[] = [
    ['OPENAI_API_KEY', 'Key from a dedicated OpenAI project with a hard spend limit.', ''],
    [
      'CHAT_SECRET',
      'Signs visitor sessions. Generated by askdare init; use a different one in production.',
      randomBytes(32).toString('base64url'),
    ],
    ['ASKDARE_MODEL', 'A current OpenAI model your project may use.', model ?? ''],
  ];
  const lines: string[] = [];
  const added: string[] = [];
  const values: Record<string, string | undefined> = { ...known };
  for (const [name, comment, value] of variables) {
    if (Object.hasOwn(known, name)) continue;
    lines.push(`# ${comment}`, `${name}=${value}`);
    added.push(name === 'CHAT_SECRET' ? 'CHAT_SECRET (generated)' : name);
    values[name] = value;
  }
  const empty = variables.map(([name]) => name).filter((name) => values[name] === '');
  if (lines.length === 0) return { added, empty };
  const separator =
    current === '' || current.endsWith('\n\n') ? '' : current.endsWith('\n') ? '\n' : '\n\n';
  await appendFile(file, `${separator}# askdare\n${lines.join('\n')}\n`, { mode: 0o600 });
  return { added, empty };
}

/** Puts the loader before `</body>` of the root layout, if there is exactly one. */
async function addScript(project: Project, botId: string): Promise<'added' | 'present' | 'manual'> {
  const layout = findFile(project.appDir, 'layout');
  if (layout === undefined) return 'manual';
  const text = await readFile(layout, 'utf8');
  if (text.includes('/api/chat/widget.js')) return 'present';
  const matches = [...text.matchAll(/^([ \t]*)(.*?)<\/body>/gm)];
  if (matches.length !== 1 || matches[0] === undefined) return 'manual';
  const [match] = matches;
  const script = `<script src="/api/chat/widget.js?bot=${botId}" async />`;
  const at = match.index + match[0].length - '</body>'.length;
  // On its own line before `</body>`, or inline as in `<body>{children}</body>`.
  const tag = match[2] === '' ? `  ${script}\n${match[1]}` : script;
  await writeFile(layout, `${text.slice(0, at)}${tag}${text.slice(at)}`);
  return 'added';
}

const AGENT_RULES = `<!-- BEGIN:askdare-agent-rules -->

## Website chat (askdare)

The chat uses \`@boldare/askdare\`. Before changing \`askdare.config.*\`, the \`api/chat\` route or the chat script, read \`node_modules/@boldare/askdare/llms.txt\` and the guide it points to; they match the installed version. After a change, run \`npx @boldare/askdare doctor\`.

<!-- END:askdare-agent-rules -->
`;

/** Points AI coding agents at the docs in the package, next to the block Next.js writes. */
async function addAgentRules(project: Project): Promise<boolean> {
  const file = join(project.root, 'AGENTS.md');
  const text = await readText(file);
  if (text.includes('BEGIN:askdare-agent-rules')) return false;
  await writeFile(file, text === '' ? AGENT_RULES : `${text.trimEnd()}\n\n${AGENT_RULES}`);
  return true;
}

/**
 * `askdare init`: the route, a bot config, `.env.local`, the script tag and a note for AI coding
 * agents. Never overwrites what is there.
 */
export async function init(options: InitOptions): Promise<void> {
  const { print, botId } = options;
  if (!BOT_ID.test(botId)) {
    throw new InitError('The bot ID may only use a-z, 0-9 and hyphens (up to 48 characters).');
  }
  const project = await readProject(options.root);
  if (project.dependencies === undefined) {
    throw new InitError('No package.json here. Run init in the folder of your Next.js app.');
  }
  if (project.dependencies['next'] === undefined) {
    throw new InitError('This is not a Next.js app (no "next" dependency). Create one first.');
  }
  if (project.appDir === undefined) {
    throw new InitError('askdare needs the App Router, but there is no app/ or src/app/ folder.');
  }
  print('askdare init\n');
  const extension = project.typescript ? 'ts' : 'js';

  const existingConfig = findFile(project.root, 'askdare.config');
  const config = existingConfig ?? join(project.root, `askdare.config.${extension}`);
  if (existingConfig) {
    print(`  = ${shown(project, config)} (kept)`);
  } else {
    await writeFile(config, configTemplate(botId));
    print(`  + ${shown(project, config)}`);
  }

  const dir = routeDir(project, '/api/chat') ?? '';
  const existingRoute = findFile(dir, 'route');
  if (existingRoute) {
    print(`  = ${shown(project, existingRoute)} (kept)`);
  } else {
    const route = join(dir, `route.${extension}`);
    const configImport = relative(dir, config.replace(/\.[cm]?[jt]sx?$/, ''))
      .split(sep)
      .join('/');
    await mkdir(dirname(route), { recursive: true });
    await writeFile(route, routeTemplate(configImport));
    print(`  + ${shown(project, route)}`);
  }

  // A generated secret must never land in git, nor the production one doctor reads.
  const ignored = await Promise.all(
    ['.env.local', '.env.production.local'].map((file) => gitIgnores(project.root, file)),
  );
  if (!ignored.every(Boolean)) {
    await appendFile(join(project.root, '.gitignore'), '\n# local secrets\n.env*.local\n');
    print('  + .gitignore: .env*.local');
  }
  const { added, empty } = await addEnv(project, options.model);
  print(added.length > 0 ? `  + .env.local: ${added.join(', ')}` : '  = .env.local (kept)');

  const script = await addScript(project, botId);
  const layout = findFile(project.appDir, 'layout');
  if (script === 'added' && layout) print(`  + ${shown(project, layout)}: the chat script`);
  if (script === 'present' && layout)
    print(`  = ${shown(project, layout)} (already loads the chat)`);
  if (await addAgentRules(project))
    print('  + AGENTS.md: where AI coding agents find the askdare docs');

  const steps: string[] = [];
  const missing = ['@boldare/askdare', 'zod'].filter((name) => !project.dependencies?.[name]);
  if (missing.length > 0) steps.push(`Install: ${addCommand(project, missing)}`);
  if ((majorOf(project.dependencies['zod']) ?? 4) < 4) {
    steps.push(`askdare needs zod 4: ${addCommand(project, ['zod@^4.1'])}`);
  }
  if (empty.length > 0) steps.push(`In .env.local, set ${empty.join(', ')}.`);
  if (script === 'manual') {
    steps.push(
      `Load the chat on your pages, e.g. in the root layout's <body>:\n       <script src="/api/chat/widget.js?bot=${botId}" async />`,
    );
  }
  steps.push(
    `Start the app (${runScript(project, 'dev')}), then check it: npx @boldare/askdare doctor`,
  );
  steps.push(
    `To embed the chat on another site, add that site to allowedOrigins and paste:\n       <script src="https://<your app>/api/chat/widget.js?bot=${botId}" async></script>`,
  );
  print('\nNext:');
  steps.forEach((step, index) => {
    print(`  ${index + 1}. ${step}`);
  });
}
